function testRecoversNegativeLambda(testCase)
    lam = -0.5;
    opts = struct( ...
        'odefun', @(t, x) lam * x, ...
        'x0', 1.0, ...
        'T_interval', [0, 40], ...
        'lya_dt', 0.5, ...
        'd0', 1e-6, ...
        'seed', 7, ...
        'ode_solver', @ode45, ...
        'ode_options', odeset('RelTol', 1e-9, 'AbsTol', 1e-11));
    r = benettin_lle_ode(opts);
    testCase.verifyEqual(r.status, 'ok');
    testCase.verifyEqual(r.LLE, lam, 'AbsTol', 2e-3);
end

