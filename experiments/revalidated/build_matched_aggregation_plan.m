function plan = build_matched_aggregation_plan(analysis_set)
%BUILD_MATCHED_AGGREGATION_PLAN  Phase 5A matched-seed contrast configuration.
%
%   plan = build_matched_aggregation_plan(analysis_set)
%
% analysis_set:
%   'confirmatory'       — primary mechanism contrasts + benchmarks
%   'sfa_sensitivity'    — fixed-context SFA profile contrasts
%   'feature_exploratory' — descriptive tables only (no contrasts / inference)
%
% Pure configuration helper: no aggregation, no inference, no p-values.
% Seed-level contrasts are defined here; Phase 5B owns statistical inference.
%
% See also: mechanism_ablation_config, EXPERIMENT_PREREGISTRATION.md

    if nargin < 1 || isempty(analysis_set)
        analysis_set = 'confirmatory';
    end
    analysis_set = char(lower(string(analysis_set)));
    switch analysis_set
        case {'confirmatory', 'sfa_sensitivity', 'feature_exploratory'}
            % ok
        otherwise
            error('build_matched_aggregation_plan:InvalidAnalysisSet', ...
                ['analysis_set must be ''confirmatory'', ''sfa_sensitivity'', ', ...
                 'or ''feature_exploratory'', got %s.'], analysis_set);
    end

    % --- Protocol / policy (common to all analysis sets) ---
    plan = struct();
    plan.protocol_version = 'matched_seed_contrasts_v1';
    plan.independent_unit = 'base_seed';
    plan.cell_pairing = 'same_base_seed';
    plan.stratum_weighting = 'equal_within_seed';
    plan.feature_weighting = 'equal_x_r_when_marginalized';
    plan.missing_data_policy = 'fail_closed_no_imputation_no_pairwise_deletion';
    plan.failed_cell_policy = 'fail_closed';
    plan.duplicate_policy = 'reject';
    plan.origin_replication_policy = ...
        'origins_are_repeated_forecasts_not_independent_units';
    plan.shared_baseline_policy = ...
        'one_unique_baseline_record_per_base_seed_and_task';
    plan.primary_estimator = 'mean_seed_level_contrast';
    plan.robust_sensitivity_estimator = 'median_seed_level_contrast';
    plan.inference_deferred_to_phase_5b = true;
    plan.no_outcome_dependent_contrasts = true;
    plan.analysis_set = analysis_set;

    plan.endpoints = build_endpoints();
    plan.non_autonomous_endpoint_ids = { ...
        'mc_total', ...
        'narma_test_nrmse', ...
        'mg_onestep_test_nrmse', ...
        'empirical_convergence_slope_per_time', ...
        'wall_time_seconds'};
    plan.autonomous_endpoint_ids = { ...
        'mg_autonomous_full_nrmse', ...
        'mg_autonomous_restricted_valid_horizon', ...
        'mg_autonomous_fixed_horizon_nrmse'};

    switch analysis_set
        case 'confirmatory'
            plan.inference_allowed = true;
            plan.contrasts = build_confirmatory_contrasts( ...
                plan.non_autonomous_endpoint_ids, plan.autonomous_endpoint_ids);
            plan.benchmark_contrasts = build_benchmark_contrasts();
            plan.notes = [ ...
                'Confirmatory analysis set: preregistered matched-seed mechanism ', ...
                'contrasts and benchmark comparisons. Aggregation produces ', ...
                'seed-level contrasts only; inference is deferred to Phase 5B.'];

        case 'sfa_sensitivity'
            plan.inference_allowed = true;
            plan.contrasts = build_sfa_sensitivity_contrasts( ...
                plan.non_autonomous_endpoint_ids, plan.autonomous_endpoint_ids);
            plan.benchmark_contrasts = {};
            plan.notes = [ ...
                'SFA sensitivity analysis set: fixed context STD=off, D=ode_off, ', ...
                'F in {x,r}. Contrasts compare multiscale SFA against single-scale ', ...
                'and dimension-control profiles. Inference allowed but deferred ', ...
                'to Phase 5B; no p-values computed here.'];

        case 'feature_exploratory'
            plan.inference_allowed = false;
            plan.contrasts = {};
            plan.benchmark_contrasts = {};
            plan.notes = [ ...
                'Feature exploratory analysis set: only descriptive cell tables ', ...
                'are produced. No matched-seed contrasts, no benchmark contrasts, ', ...
                'and inference_allowed=false.'];
    end
end

