function contrasts = build_confirmatory_contrasts(nonauto_ids, auto_ids)
% Ten preregistered confirmatory contrasts (primary / supportive /
% representation / interaction). Factors: A, S, D, F.

    both_ids = [nonauto_ids, auto_ids];
    contrasts = {};

    % --- Primary mechanism ---

    % 1. SFA timescale distribution (three vs moment-matched single)
    contrasts{end+1} = make_contrast( ... %#ok<*AGROW>
        'sfa_timescale_distribution', ...
        'primary_mechanism', ...
        'primary', ...
        make_factors('three_timescales', '', '', ''), ...
        make_factors('single_moment_matched', '', '', ''), ...
        {'S', 'D', 'F'}, ...
        {}, ...
        'simple_marginal', ...
        both_ids, ...
        8, 4, true, ...
        ['Matched-seed contrast of multi-timescale excitatory SFA versus ', ...
         'moment-matched single timescale, holding S, D, F fixed.'], ...
        ['Do not interpret as a pure presence-of-SFA effect; control already ', ...
         'has SFA (single moment-matched).'], ...
        '');

    % 2. STD main effect
    contrasts{end+1} = make_contrast( ...
        'std_main_effect', ...
        'primary_mechanism', ...
        'primary', ...
        make_factors('', 'on', '', ''), ...
        make_factors('', 'off', '', ''), ...
        {'A', 'D', 'F'}, ...
        {}, ...
        'simple_marginal', ...
        both_ids, ...
        12, 6, true, ...
        'Matched-seed main effect of STD (on vs off), holding A, D, F fixed.', ...
        'Do not attribute jointly with changes in A or D.', ...
        '');

    % 3. Delay main effect (non-autonomous only)
    contrasts{end+1} = make_contrast( ...
        'delay_main_effect', ...
        'primary_mechanism', ...
        'primary', ...
        make_factors('', '', 'dde_on', ''), ...
        make_factors('', '', 'ode_off', ''), ...
        {'A', 'S', 'F'}, ...
        {}, ...
        'simple_marginal', ...
        nonauto_ids, ...
        12, NaN, false, ...
        'Matched-seed main effect of delay (DDE vs ODE), holding A, S, F fixed.', ...
        ['Prohibited on autonomous endpoints (D must be ode_off). Do not ', ...
         'conflate with architecture or STD effects.'], ...
        '');

    % 4. Combined architecture system contrast (never one-mechanism attribution)
    contrasts{end+1} = make_contrast( ...
        'combined_architecture_system_contrast', ...
        'primary_mechanism', ...
        'primary', ...
        make_factors('three_timescales', 'on', 'dde_on', ''), ...
        make_factors('off', 'off', 'ode_off', ''), ...
        {'F'}, ...
        {}, ...
        'system_combined', ...
        nonauto_ids, ...
        2, NaN, false, ...
        ['System-level contrast of the combined architecture (three-timescale ', ...
         'SFA + STD + DDE) versus off/off/ODE, matched on F (x and r strata).'], ...
        ['Never attribute this contrast to a single mechanism (A, S, or D). ', ...
         'Autonomous mode is forbidden because D changes.'], ...
        '');

    % --- Supportive mechanism ---

    % 5. SFA presence (moment-matched vs off)
    contrasts{end+1} = make_contrast( ...
        'sfa_presence_moment_matched', ...
        'supportive_mechanism', ...
        'supportive', ...
        make_factors('single_moment_matched', '', '', ''), ...
        make_factors('off', '', '', ''), ...
        {'S', 'D', 'F'}, ...
        {}, ...
        'simple_marginal', ...
        both_ids, ...
        8, 4, true, ...
        ['Supportive contrast of moment-matched single SFA versus adaptation ', ...
         'off, holding S, D, F fixed.'], ...
        'Do not interpret as a multi-timescale distribution effect.', ...
        '');

    % 6. Combined architecture ODE analog (autonomous only)
    contrasts{end+1} = make_contrast( ...
        'combined_architecture_ode_analog', ...
        'supportive_mechanism', ...
        'supportive', ...
        make_factors('three_timescales', 'on', 'ode_off', ''), ...
        make_factors('off', 'off', 'ode_off', ''), ...
        {'F'}, ...
        {}, ...
        'system_combined', ...
        auto_ids, ...
        NaN, 2, true, ...
        ['ODE analog of the combined architecture: three-timescale SFA + STD ', ...
         'under D=ode_off versus off/off/ode. Label: combined_architecture_ode_analog.'], ...
        ['Not a DDE system contrast; D is fixed ode_off. Never attribute to a ', ...
         'single mechanism. Non-autonomous strata are prohibited for this label.'], ...
        '');

    % --- Representation sensitivity ---

    % 7. Feature r vs x
    contrasts{end+1} = make_contrast( ...
        'feature_r_vs_x', ...
        'representation_sensitivity', ...
        'secondary', ...
        make_factors('', '', '', 'r'), ...
        make_factors('', '', '', 'x'), ...
        {'A', 'S', 'D'}, ...
        {}, ...
        'simple_marginal', ...
        both_ids, ...
        12, 6, true, ...
        'Secondary representation sensitivity: readout feature r versus x.', ...
        'Not a mechanism claim about A, S, or D.', ...
        '');

    % --- Interactions (2-way) ---

    % 8. SFA distribution × STD
    contrasts{end+1} = make_contrast( ...
        'sfa_distribution_x_std', ...
        'interaction', ...
        'interaction', ...
        make_factors('three_timescales', 'on', '', ''), ...
        make_factors('single_moment_matched', 'off', '', ''), ...
        {'D', 'F'}, ...
        {}, ...
        'interaction_2way', ...
        both_ids, ...
        4, 2, true, ...
        ['Two-way interaction of SFA distribution and STD for each matched ', ...
         '(D, F) stratum.'], ...
        'Do not report as a simple main effect of A or S.', ...
        ['[(A=three,S=on)-(A=single,S=on)] - ', ...
         '[(A=three,S=off)-(A=single,S=off)]']);

    % 9. SFA distribution × delay (non-autonomous only)
    contrasts{end+1} = make_contrast( ...
        'sfa_distribution_x_delay', ...
        'interaction', ...
        'interaction', ...
        make_factors('three_timescales', '', 'dde_on', ''), ...
        make_factors('single_moment_matched', '', 'ode_off', ''), ...
        {'S', 'F'}, ...
        {}, ...
        'interaction_2way', ...
        nonauto_ids, ...
        4, NaN, false, ...
        ['Two-way interaction of SFA distribution and delay for each matched ', ...
         '(S, F) stratum (non-autonomous only).'], ...
        'Autonomous endpoints prohibited (D varies). Not a simple A or D effect.', ...
        ['[(A=three,D=dde)-(A=single,D=dde)] - ', ...
         '[(A=three,D=ode)-(A=single,D=ode)]']);

    % 10. STD × delay (non-autonomous only)
    contrasts{end+1} = make_contrast( ...
        'std_x_delay', ...
        'interaction', ...
        'interaction', ...
        make_factors('', 'on', 'dde_on', ''), ...
        make_factors('', 'off', 'ode_off', ''), ...
        {'A', 'F'}, ...
        {}, ...
        'interaction_2way', ...
        nonauto_ids, ...
        6, NaN, false, ...
        ['Two-way interaction of STD and delay for each matched (A, F) stratum ', ...
         '(non-autonomous only).'], ...
        'Autonomous endpoints prohibited (D varies). Not a simple S or D effect.', ...
        ['[(S=on,D=dde)-(S=off,D=dde)] - ', ...
         '[(S=on,D=ode)-(S=off,D=ode)]']);
end

% =============================================================================
% SFA sensitivity contrasts
% =============================================================================

function contrasts = build_sfa_sensitivity_contrasts(nonauto_ids, auto_ids)
% Fixed context: S=off, D=ode_off, F in {x,r}. Match on F → 2 strata.
% All contrasts allow autonomous (D already ode_off).

    both_ids = [nonauto_ids, auto_ids];
    fixed_note = 'Fixed context: S=off, D=ode_off; matched on F (x,r).';
    contrasts = {};

    % 1–5. Multiscale vs profile controls (treatment always three_timescales)
    profile_controls = { ...
        'single_fast', ...
        'single_middle', ...
        'single_slow', ...
        'single_moment_matched', ...
        'three_identical_dimension_control'};
    for i = 1:numel(profile_controls)
        ctrl = profile_controls{i};
        contrasts{end+1} = make_contrast( ...
            sprintf('multiscale_vs_%s', ctrl), ...
            'primary_mechanism', ...
            'primary', ...
            make_factors('three_timescales', 'off', 'ode_off', ''), ...
            make_factors(ctrl, 'off', 'ode_off', ''), ...
            {'F'}, ...
            {}, ...
            'simple_marginal', ...
            both_ids, ...
            2, 2, true, ...
            sprintf(['%s Treatment A=three_timescales versus control A=%s.'], ...
                fixed_note, ctrl), ...
            ['Do not generalize beyond the fixed S=off, D=ode_off context. ', ...
             'Not a confirmatory delay or STD claim.'], ...
            '');
    end

    % 6. Equivalence diagnostic: three_identical vs single_moment_matched
    contrasts{end+1} = make_contrast( ...
        'single_moment_vs_three_identical_equivalence_check', ...
        'equivalence_diagnostic', ...
        'equivalence_diagnostic', ...
        make_factors('three_identical_dimension_control', 'off', 'ode_off', ''), ...
        make_factors('single_moment_matched', 'off', 'ode_off', ''), ...
        {'F'}, ...
        {}, ...
        'equivalence_diagnostic', ...
        both_ids, ...
        2, 2, true, ...
        [fixed_note, ' Dimension-control equivalence check: ', ...
         'three_identical_dimension_control versus single_moment_matched.'], ...
        ['DO NOT treat failure to reject zero as proof of equivalence. ', ...
         'Descriptive / diagnostic only; no TOST or equivalence declaration here.'], ...
        '');
end

