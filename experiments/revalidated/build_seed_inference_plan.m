function plan = build_seed_inference_plan(analysis_set)
%BUILD_SEED_INFERENCE_PLAN  Frozen Phase 5B seed-level inference protocol.
%
%   plan = build_seed_inference_plan(analysis_set)
%
% Pure configuration: no outcomes, no statistics, no dynamic hypothesis selection.
% Phase 5B-B executes inference from this plan and Phase 5A contrast tables.
%
% analysis_set:
%   'confirmatory'        — primary + secondary + benchmark families
%   'sfa_sensitivity'     — SFA sensitivity family only
%   'feature_exploratory' — estimate-only policy; no testing families
%
% See also: mechanism_ablation_config, build_matched_aggregation_plan

    if nargin < 1 || isempty(analysis_set)
        analysis_set = 'confirmatory';
    end
    analysis_set = char(lower(string(analysis_set)));
    switch analysis_set
        case {'confirmatory', 'sfa_sensitivity', 'feature_exploratory'}
            % ok
        otherwise
            error('build_seed_inference_plan:InvalidAnalysisSet', ...
                ['analysis_set must be ''confirmatory'', ''sfa_sensitivity'', ', ...
                 'or ''feature_exploratory'', got %s.'], analysis_set);
    end

    plan = struct();
    plan.protocol_version = 'seed_level_inference_v1';
    plan.independent_unit = 'base_seed';
    plan.alpha = 0.05;
    plan.alternative = 'two_sided';
    plan.primary_estimator = 'mean_oriented_seed_effect';
    plan.robust_estimator = 'median_oriented_seed_effect';
    plan.ci_method = 'nonparametric_seed_bootstrap_percentile';
    plan.bootstrap_replicates = 20000;
    plan.bootstrap_ci_percent = 95;
    plan.randomization_test = 'paired_sign_flip_mean_statistic';
    plan.sign_flip_exact_max_n = 16;
    plan.sign_flip_monte_carlo_replicates = 100000;
    plan.monte_carlo_pvalue_rule = 'plus_one';
    plan.multiplicity_method = 'holm_bonferroni';
    plan.rng_algorithm = 'mt19937ar_local_stream';
    plan.rng_master_seed = 55021;
    plan.global_rng_mutation_forbidden = true;
    plan.missing_data_policy = 'fail_closed_no_imputation_no_pairwise_deletion';
    plan.claim_direction = 'positive_oriented_effect_is_favorable';
    plan.superiority_rule = [ ...
        'holm_reject_and_oriented_mean_positive_and_ci_lower_positive'];
    plan.fixed_horizon_policy = ...
        'descriptive_pointwise_estimates_no_pointwise_hypothesis_tests';
    plan.smoke_pilot_policy = 'diagnostic_only_never_publication_inference';
    plan.analysis_set = analysis_set;

    plan.paired_effect_definitions = struct( ...
        'delta_raw', 'treatment_i - control_i', ...
        'effect_oriented', 'orientation_multiplier * delta_raw', ...
        'primary_estimator', 'mean(effect_oriented_i)', ...
        'robust_estimator', 'median(effect_oriented_i)', ...
        'dz', 'mean(effect_oriented_i) / std(effect_oriented_i, 0)', ...
        'dz_zero_variance_status', 'zero_variance_undefined', ...
        'common_language', [ ...
            'mean(effect_oriented_i > 0) + 0.5 * mean(effect_oriented_i == 0)'], ...
        'rank_biserial', [ ...
            'matched-pairs rank-biserial on nonzero absolute differences']);

    plan.paired_quantities = { ...
        'paired_raw_mean_difference', ...
        'paired_oriented_mean_effect', ...
        'paired_median_difference', ...
        'matched_pairs_rank_biserial_correlation', ...
        'paired_standardized_mean_effect_dz', ...
        'common_language_favorable_effect_probability'};

    plan.claim_statuses = { ...
        'favorable_supported', ...
        'significant_unfavorable', ...
        'not_statistically_resolved', ...
        'estimate_only', ...
        'diagnostic_only_not_for_publication', ...
        'failed_inference_validation'};

    plan.claim_rule = struct( ...
        'favorable_superiority_requires', {{ ...
            'protocol_tier_publication', ...
            'exact_30_publication_seeds', ...
            'structural_validations_pass', ...
            'holm_adjusted_rejection', ...
            'oriented_mean_positive', ...
            'bootstrap_ci_lower_positive', ...
            'no_forbidden_provenance_or_override'}}, ...
        'estimate_only_fields', struct( ...
            'p_value', NaN, ...
            'p_adjusted', NaN, ...
            'holm_reject', false, ...
            'inference_action', 'estimate_only', ...
            'claim_allowed', false));

    plan.dimension_control_equivalence = struct( ...
        'contrast_id', 'single_moment_vs_three_identical_equivalence_check', ...
        'label', 'numerical_dimension_control_check_not_statistical_equivalence', ...
        'absolute_tolerance', 1e-8, ...
        'relative_tolerance', 1e-6, ...
        'allowed_error_formula', [ ...
            'absolute_tolerance + relative_tolerance * ', ...
            'max(abs(treatment_value), abs(control_value))'], ...
        'pass_criterion', 'abs(delta_raw) <= allowed_error', ...
        'gated_endpoint_ids', {{ ...
            'mc_total', ...
            'narma_test_nrmse', ...
            'mg_onestep_test_nrmse'}}, ...
        'autonomous_endpoints_excluded', true, ...
        'prohibited_interpretations', {{ ...
            'failure_to_reject_zero', ...
            'tost', ...
            'post_hoc_sesoi', ...
            'p_greater_than_alpha_as_equivalence'}});

    plan.hypothesis_registry = build_hypothesis_registry(analysis_set);
    plan.testing_families = build_testing_families(analysis_set);

    validate_seed_inference_plan(plan);
end

% =============================================================================
% Hypothesis registry
% =============================================================================

function registry = build_hypothesis_registry(analysis_set)
    registry = {};

    switch analysis_set
        case 'confirmatory'
            registry = [registry, ...
                build_primary_mechanism_hypotheses(), ...
                build_conventional_esn_benchmark_hypotheses(), ...
                build_secondary_mechanism_hypotheses(), ...
                build_estimate_only_hypotheses_confirmatory()];

        case 'sfa_sensitivity'
            registry = [registry, ...
                build_sfa_sensitivity_hypotheses(), ...
                build_estimate_only_hypotheses_sfa_sensitivity()];

        case 'feature_exploratory'
            registry = {build_feature_exploratory_policy_entry()};
    end
end

function hyps = build_primary_mechanism_hypotheses()
    contrast_ids = { ...
        'sfa_timescale_distribution', ...
        'std_main_effect', ...
        'delay_main_effect', ...
        'combined_architecture_system_contrast'};
    endpoint_ids = {'mc_total', 'narma_test_nrmse', 'mg_onestep_test_nrmse'};
    hyps = {};
    for c = 1:numel(contrast_ids)
        for e = 1:numel(endpoint_ids)
            hyps{end+1} = make_hypothesis( ... %#ok<AGROW>
                'seed_contrast', ...
                contrast_ids{c}, ...
                endpoint_ids{e}, ...
                '', ...
                '', ...
                'confirmatory_primary_mechanism_performance', ...
                'test_and_holm', ...
                'confirmatory', ...
                primary_role_for(contrast_ids{c}), ...
                primary_interpretation(contrast_ids{c}, endpoint_ids{e}), ...
                primary_prohibited(contrast_ids{c}));
        end
    end
end

function hyps = build_conventional_esn_benchmark_hypotheses()
    entries = { ...
        'one_step_combined_architecture', 'narma_test_nrmse', ...
            'conventional_leaky_esn', ''; ...
        'one_step_combined_architecture', 'mg_onestep_test_nrmse', ...
            'conventional_leaky_esn', ''; ...
        'autonomous_ode_analog', 'mg_autonomous_full_nrmse', ...
            'conventional_leaky_esn', ''; ...
        'autonomous_ode_analog', 'mg_autonomous_restricted_valid_horizon', ...
            'conventional_leaky_esn', ''};
    hyps = {};
    for i = 1:size(entries, 1)
        hyps{end+1} = make_hypothesis( ... %#ok<AGROW>
            'benchmark_contrast', ...
            entries{i, 1}, ...
            entries{i, 2}, ...
            entries{i, 3}, ...
            entries{i, 4}, ...
            'conventional_esn_benchmark', ...
            'test_and_holm', ...
            'confirmatory', ...
            'benchmark', ...
            benchmark_interpretation(entries{i, 1}, entries{i, 2}, entries{i, 3}), ...
            ['Not a single-mechanism attribution. Autonomous ODE analog only; ', ...
             'never describe as DDE autonomous result.']);
    end
end

function hyps = build_secondary_mechanism_hypotheses()
    nonauto_contrasts = { ...
        'sfa_presence_moment_matched', ...
        'feature_r_vs_x', ...
        'sfa_distribution_x_std', ...
        'sfa_distribution_x_delay', ...
        'std_x_delay'};
    nonauto_endpoints = {'mc_total', 'narma_test_nrmse', 'mg_onestep_test_nrmse'};
    auto_contrasts = { ...
        'sfa_timescale_distribution', ...
        'std_main_effect', ...
        'sfa_presence_moment_matched', ...
        'combined_architecture_ode_analog', ...
        'feature_r_vs_x', ...
        'sfa_distribution_x_std'};
    auto_endpoints = { ...
        'mg_autonomous_full_nrmse', ...
        'mg_autonomous_restricted_valid_horizon'};

    hyps = {};
    for c = 1:numel(nonauto_contrasts)
        for e = 1:numel(nonauto_endpoints)
            hyps{end+1} = make_hypothesis( ... %#ok<AGROW>
                'seed_contrast', ...
                nonauto_contrasts{c}, ...
                nonauto_endpoints{e}, ...
                '', ...
                '', ...
                'confirmatory_secondary_mechanism', ...
                'test_and_holm', ...
                'confirmatory', ...
                secondary_role_for(nonauto_contrasts{c}), ...
                secondary_interpretation(nonauto_contrasts{c}, nonauto_endpoints{e}), ...
                secondary_prohibited(nonauto_contrasts{c}, false));
        end
    end
    for c = 1:numel(auto_contrasts)
        for e = 1:numel(auto_endpoints)
            hyps{end+1} = make_hypothesis( ... %#ok<AGROW>
                'seed_contrast', ...
                auto_contrasts{c}, ...
                auto_endpoints{e}, ...
                '', ...
                '', ...
                'confirmatory_secondary_mechanism', ...
                'test_and_holm', ...
                'confirmatory', ...
                secondary_role_for(auto_contrasts{c}), ...
                ['ODE analog autonomous comparison for ', auto_contrasts{c}, ...
                 ' on ', auto_endpoints{e}, '.'], ...
                secondary_prohibited(auto_contrasts{c}, true));
        end
    end
end

