function h = make_hypothesis(source_table, contrast_id, endpoint_id, ...
        baseline_name, horizon_rule, multiplicity_family, inference_action, ...
        expected_analysis_set, expected_contrast_role, interpretation, ...
        prohibited_interpretation)
    h = struct();
    h.source_table = source_table;
    h.contrast_id = contrast_id;
    h.endpoint_id = endpoint_id;
    if ~isempty(baseline_name)
        h.baseline_name = baseline_name;
    end
    if ~isempty(horizon_rule)
        h.horizon_rule = horizon_rule;
    end
    h.multiplicity_family = multiplicity_family;
    h.inference_action = inference_action;
    h.expected_analysis_set = expected_analysis_set;
    h.expected_contrast_role = expected_contrast_role;
    h.interpretation = interpretation;
    h.prohibited_interpretation = prohibited_interpretation;
end

function role = primary_role_for(contrast_id)
    switch contrast_id
        case {'sfa_timescale_distribution', 'std_main_effect', ...
                'delay_main_effect', 'combined_architecture_system_contrast'}
            role = 'primary';
        otherwise
            role = 'primary';
    end
end

function txt = primary_interpretation(contrast_id, endpoint_id)
    txt = sprintf('Confirmatory primary mechanism: %s on %s.', ...
        contrast_id, endpoint_id);
end

function txt = primary_prohibited(contrast_id)
    switch contrast_id
        case 'combined_architecture_system_contrast'
            txt = 'Never attribute to a single mechanism (A, S, or D).';
        case 'delay_main_effect'
            txt = 'Autonomous endpoints prohibited for delay main effect.';
        otherwise
            txt = 'Do not conflate with other simultaneous factor changes.';
    end
end

function role = secondary_role_for(contrast_id)
    switch contrast_id
        case {'sfa_presence_moment_matched', 'combined_architecture_ode_analog'}
            role = 'supportive';
        case 'feature_r_vs_x'
            role = 'secondary';
        case {'sfa_distribution_x_std', 'sfa_distribution_x_delay', 'std_x_delay'}
            role = 'interaction';
        otherwise
            role = 'primary';
    end
end

function txt = secondary_interpretation(contrast_id, endpoint_id)
    txt = sprintf('Confirmatory secondary mechanism: %s on %s.', ...
        contrast_id, endpoint_id);
end

function txt = secondary_prohibited(contrast_id, is_autonomous)
    if is_autonomous
        if strcmp(contrast_id, 'combined_architecture_ode_analog')
            txt = 'ODE analog only; not a DDE autonomous result.';
        else
            txt = 'Autonomous ODE analog; D must be ode_off.';
        end
    else
        txt = 'Not a simple main effect of a single manipulated factor.';
    end
end

function txt = benchmark_interpretation(contrast_id, endpoint_id, baseline)
    txt = sprintf('Conventional ESN benchmark: %s vs %s on %s.', ...
        contrast_id, baseline, endpoint_id);
    if strcmp(contrast_id, 'autonomous_ode_analog')
        txt = [txt, ' Label: ODE analog.'];
    end
end
