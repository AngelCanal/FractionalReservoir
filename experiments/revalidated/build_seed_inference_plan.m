end

function hyps = build_estimate_only_hypotheses_confirmatory()
    hyps = {};

    % Diagnostic / cost endpoints (representative seed-contrast rows)
    diag_endpoints = {'empirical_convergence_slope_per_time', 'wall_time_seconds'};
    diag_contrast = 'sfa_timescale_distribution';
    for e = 1:numel(diag_endpoints)
        hyps{end+1} = make_hypothesis( ... %#ok<AGROW>
            'seed_contrast', diag_contrast, diag_endpoints{e}, '', '', ...
            '', 'estimate_only', 'confirmatory', 'diagnostic', ...
            ['Descriptive estimate for ', diag_endpoints{e}, '.'], ...
            'No null-hypothesis test or Holm rejection for this endpoint.');
    end

    % Fixed-horizon autonomous (policy exemplar)
    hyps{end+1} = make_hypothesis( ...
        'benchmark_contrast', 'autonomous_ode_analog', ...
        'mg_autonomous_fixed_horizon_nrmse', 'conventional_leaky_esn', ...
        'fixed_horizon', '', 'estimate_only', 'confirmatory', 'benchmark', ...
        'Descriptive fixed-horizon NRMSE; no pointwise hypothesis tests.', ...
        'Do not produce uncorrected pointwise significance tests.');

    % Simple baselines (estimate-only exemplars)
    simple_baselines = { ...
        'one_step_combined_architecture', 'narma_test_nrmse', 'linear_input_history'; ...
        'one_step_combined_architecture', 'narma_test_nrmse', 'training_target_mean'; ...
        'one_step_combined_architecture', 'mg_onestep_test_nrmse', 'linear_autoregression'; ...
        'one_step_combined_architecture', 'mg_onestep_test_nrmse', 'persistence'; ...
        'autonomous_ode_analog', 'mg_autonomous_full_nrmse', 'linear_autoregression'; ...
        'autonomous_ode_analog', 'mg_autonomous_full_nrmse', 'persistence'};
    for i = 1:size(simple_baselines, 1)
        hyps{end+1} = make_hypothesis( ... %#ok<AGROW>
            'benchmark_contrast', ...
            simple_baselines{i, 1}, ...
            simple_baselines{i, 2}, ...
            simple_baselines{i, 3}, ...
            '', ...
            '', ...
            'estimate_only', ...
            'confirmatory', ...
            'benchmark', ...
            ['Descriptive benchmark vs ', simple_baselines{i, 3}, '.'], ...
            'No superiority claim from simple baseline comparisons.');
    end

    % Equivalence diagnostic
    hyps{end+1} = make_hypothesis( ...
        'seed_contrast', ...
        'single_moment_vs_three_identical_equivalence_check', ...
        'mc_total', '', '', '', ...
        'estimate_only', 'sfa_sensitivity', 'equivalence_diagnostic', ...
        'Numerical dimension-control check; not statistical equivalence.', ...
        ['Do not use failure to reject zero, TOST, or p>0.05 as equivalence ', ...
         'evidence.']);
end

function hyps = build_estimate_only_hypotheses_sfa_sensitivity()
    hyps = {make_hypothesis( ...
        'seed_contrast', ...
        'single_moment_vs_three_identical_equivalence_check', ...
        'narma_test_nrmse', '', '', '', ...
        'estimate_only', 'sfa_sensitivity', 'equivalence_diagnostic', ...
        'Numerical dimension-control check; not statistical equivalence.', ...
        'Do not use failure to reject zero, TOST, or p>0.05 as equivalence evidence.')};
end

function entry = build_feature_exploratory_policy_entry()
    entry = make_hypothesis( ...
        '', '', '', '', '', '', ...
        'estimate_only', 'feature_exploratory', 'exploratory', ...
        'Feature exploratory tables are descriptive only.', ...
        'No testing family; never confirmatory inference.');
    entry.registry_role = 'analysis_set_policy';
end

