function cfg = mechanism_ablation_config(mode, analysis_set)
% mechanism_ablation_config  Preregistered MESN mechanism-ablation matrix.
%
%   cfg = mechanism_ablation_config()
%   cfg = mechanism_ablation_config('smoke')
%   cfg = mechanism_ablation_config('pilot')
%   cfg = mechanism_ablation_config('publication')
%   cfg = mechanism_ablation_config('full')                 % alias for publication
%   cfg = mechanism_ablation_config(mode, analysis_set)
%
% analysis_set (orthogonal to protocol_tier):
%   'confirmatory'      — 24 cells/seed (default publication family)
%   'sfa_sensitivity'   — 12 cells/seed (restricted SFA context)
%   'feature_exploratory' — exploratory all-feature cells (not confirmatory)
%
% protocol_tier remains only: smoke | pilot | publication
%
% Adaptation profiles are explicit (tau_a / c_a vectors); publication profiles
% never obtain tau_a from default_MESN_config logspace.
%
% Manipulated multiscale mechanism:
%   multi-timescale excitatory SFA with a common single-timescale inhibitory SFA.
% Do not call this fully multiscale E/I adaptation.
%
% Moment-matched control (equal-weight three-timescale bank):
%   tau da_k/dt = r - a_k,  adaptation output = sum_k c_k a_k
%   total DC coupling = sum(c_k)
%   tau_eff = sum(c_k*tau_k)/sum(c_k) = (0.25+2.5+25)/3 = 9.25
% Matches total coupling and first temporal moment only — not every frequency.
%
% See also: docs/validation/EXPERIMENT_PREREGISTRATION.md

    if nargin < 1 || isempty(mode)
        mode = 'publication';
    end
    if nargin < 2 || isempty(analysis_set)
        analysis_set = 'confirmatory';
    end
    mode = char(mode);
    mode_in = lower(mode);
    analysis_set = char(lower(string(analysis_set)));

    switch mode_in
        case 'full'
            mode_in = 'publication';
        case {'smoke', 'pilot', 'publication'}
            % ok
        otherwise
            error('mechanism_ablation_config:InvalidMode', ...
                'mode must be ''smoke'', ''pilot'', ''publication'', or ''full'', got %s.', mode);
    end
    switch analysis_set
        case {'confirmatory', 'sfa_sensitivity', 'feature_exploratory'}
            % ok
        otherwise
            error('mechanism_ablation_config:InvalidAnalysisSet', ...
                ['analysis_set must be ''confirmatory'', ''sfa_sensitivity'', ', ...
                 'or ''feature_exploratory'', got %s.'], analysis_set);
    end

    % Fixed totals from resolve_adaptation_coupling defaults (T35).
    c_total_E = 0.1 / 7;
    c_total_I = 0.1 / 4;

    % Frozen single-timescale inhibitory SFA on every non-off profile.
    tau_a_I_frozen = 0.25;
    c_a_I_frozen = c_total_I;

    cfg = struct();
    cfg.experiment_name = 'mechanism_ablation';
    cfg.preregistration_doc = 'docs/validation/EXPERIMENT_PREREGISTRATION.md';
    cfg.mode = mode_in;
    cfg.protocol_tier = mode_in;
    cfg.active_analysis_set = analysis_set;
    cfg.created_utc = char(datetime('now', 'TimeZone', 'UTC', ...
        'Format', 'yyyy-MM-dd''T''HH:mm:ss''Z'''));

    cfg.c_total_E = c_total_E;
    cfg.c_total_I = c_total_I;
    cfg.tau_a_I_frozen = tau_a_I_frozen;
    cfg.c_a_I_frozen = c_a_I_frozen;
    cfg.moment_matched_tau_E = 9.25;
    cfg.manipulated_mechanism = [ ...
        'multi-timescale excitatory SFA with a common single-timescale ', ...
        'inhibitory SFA'];
    cfg.fairness_rule = [ ...
        'Keep sum(c_a_E)=c_total_E and sum(c_a_I)=c_total_I across non-off ', ...
        'profiles. Explicit tau_a vectors only (no publication logspace). ', ...
        'Moment-matched single E filter uses tau_a_E=9.25 = mean([0.25,2.5,25]) ', ...
        'for equal weights (DC + first temporal moment only). Inhibitory SFA is ', ...
        'frozen at tau_a_I=0.25 with coupling c_total_I on all non-off profiles.'];

    cfg.adaptation_profiles = build_adaptation_profiles(c_total_E, c_total_I, ...
        tau_a_I_frozen, c_a_I_frozen);
    cfg.feature_policy = build_feature_policy();

    std_levels = { ...
        struct('label', 'off', 'n_b_E', 0, 'n_b_I', 0), ...
        struct('label', 'on',  'n_b_E', 1, 'n_b_I', 1) ...
        };
    delay_levels = { ...
        struct('label', 'ode_off', 'lags', []), ...
        struct('label', 'dde_on',  'lags', 0.03) ...
        };
    feature_levels = { ...
        feature_level_from_policy(cfg.feature_policy, 'x'), ...
        feature_level_from_policy(cfg.feature_policy, 'r'), ...
        feature_level_from_policy(cfg.feature_policy, 'all') ...
        };

    %% Analysis-set definitions (orthogonal to protocol_tier)
    confirmatory_adapt = profiles_by_label(cfg.adaptation_profiles, ...
        {'off', 'single_moment_matched', 'three_timescales'});
    sensitivity_adapt = profiles_by_label(cfg.adaptation_profiles, ...
        {'single_fast', 'single_middle', 'single_slow', ...
         'single_moment_matched', 'three_timescales', ...
         'three_identical_dimension_control'});

    cfg.analysis_set_definitions = struct();
    cfg.analysis_set_definitions.confirmatory = struct( ...
        'adaptation_labels', {{'off', 'single_moment_matched', 'three_timescales'}}, ...
        'std_labels', {{'off', 'on'}}, ...
        'delay_labels', {{'ode_off', 'dde_on'}}, ...
        'feature_labels', {{'x', 'r'}}, ...
        'expected_n_cells', 24, ...
        'notes', '3 x 2 x 2 x 2 confirmatory architecture family');
    cfg.analysis_set_definitions.sfa_sensitivity = struct( ...
        'adaptation_labels', {{'single_fast', 'single_middle', 'single_slow', ...
            'single_moment_matched', 'three_timescales', ...
            'three_identical_dimension_control'}}, ...
        'std_labels', {{'off'}}, ...
        'delay_labels', {{'ode_off'}}, ...
        'feature_labels', {{'x', 'r'}}, ...
        'expected_n_cells', 12, ...
        'notes', [ ...
            '6 x 1 x 1 x 2 SFA sensitivity under STD-off / ODE; ', ...
            'off reference excluded from this family (documented choice)']);
    cfg.analysis_set_definitions.feature_exploratory = struct( ...
        'adaptation_labels', {{'off', 'single_moment_matched', 'three_timescales'}}, ...
        'std_labels', {{'off'}}, ...
        'delay_labels', {{'ode_off'}}, ...
        'feature_labels', {{'all'}}, ...
        'expected_n_cells', 3, ...
        'notes', 'Exploratory unmatched all-feature cells; never confirmatory');

    cfg.n_confirmatory_cells_per_seed = ...
        cfg.analysis_set_definitions.confirmatory.expected_n_cells;
    cfg.n_sfa_sensitivity_cells_per_seed = ...
        cfg.analysis_set_definitions.sfa_sensitivity.expected_n_cells;

    %% Shared base network (paired across ablations)
    cfg.base = struct();
    cfg.base.n = 40;
    cfg.base.fraction_E = 0.5;
    cfg.base.n_inputs = 1;
    cfg.base.dt = 0.1;
    cfg.base.tau_d = 0.55;
    cfg.base.dale = true;
    cfg.base.row_center_W = false;
    cfg.base.W_scale_method = 'abscissa';
    cfg.base.level_of_chaos = 1.0;          % may be overridden by T102 calibration
    cfg.base.input_scaling = 0.5;           % may be overridden by T102 calibration
    cfg.base.input_sparsity = 0.8;
    cfg.base.input_mask_mode = 'fixed_count';  % publication-safe; Bernoulli retained as legacy
    cfg.base.adaptation_initialization_mode = 'paired_weighted_match';
    cfg.base.tau_b_E_rec = 0.6;
    cfg.base.tau_b_E_rel = 0.1;
    cfg.base.tau_b_I_rec = 0.4;
    cfg.base.tau_b_I_rel = 0.5;
    cfg.base.include_input = false;
    cfg.base.lambda = 1e-6;

    %% Seeds
    cfg.pilot_seeds = [1729, 2718, 31415];
    cfg.full_n_seeds = 30;
    cfg.full_seeds = unique([cfg.pilot_seeds, ...
        10007, 10009, 10037, 10039, 10061, 10067, 10069, 10079, 10091, 10093, ...
        10099, 10103, 10111, 10133, 10139, 10141, 10151, 10159, 10163, 10169, ...
        10177, 10181, 10193, 10211, 10223, 10243, 10247], 'stable');
    cfg.full_seeds = cfg.full_seeds(1:cfg.full_n_seeds);

    %% Endpoints (declared before outcomes)
    cfg.primary_endpoints = { ...
        'held_out_linear_MC_curve_and_area', ...
        'narma_nrmse', ...
        'mackey_glass_one_step_nrmse', ...
        'empirical_convergence_rate', ...
        'compute_time_seconds' ...
        };
    cfg.secondary_endpoints = { ...
        'nonlinear_capacity', ...
        'frequency_discrimination', ...
        'stimulus_counting', ...
        'effective_rank', ...
        'autonomous_ode_horizon' ...
        };
    cfg.exclusions = { ...
        'invalid_fisher_metric', ...
        'dde_lle', ...
        'dde_autonomous_rollout', ...
        'uncorrected_phase_advance', ...
        'bifurcation_claims' ...
        };

    %% Sequence lengths and task options by protocol tier
    switch mode_in
        case {'smoke', 'pilot'}
            cfg.seeds = cfg.pilot_seeds;
            cfg.pilot_not_for_publication = true;
            cfg.base.n = 12;  % reduced network for pipeline QA only
            cfg.lengths = reduced_lengths();
            cfg.secondary_enabled = false;  % smoke/pilot: primary endpoints only
            if strcmp(mode_in, 'smoke')
                cfg.length_note = 'smoke_reduced_lengths_never_publication_evidence';
            else
                cfg.length_note = 'pilot_reduced_lengths_never_publication_inference';
            end
        case 'publication'
            cfg.seeds = cfg.full_seeds;
            cfg.pilot_not_for_publication = false;
            cfg.lengths = publication_lengths();
            cfg.secondary_enabled = true;
            if isfield(cfg, 'length_note')
                cfg = rmfield(cfg, 'length_note');
            end
    end

    %% Operating-point bands (T102); frozen before full experiment
    cfg.operating_point = struct();
    cfg.operating_point.mean_rate_band = [0.05, 0.85];
    cfg.operating_point.saturation_fraction_max = 0.35;
    cfg.operating_point.silent_fraction_max = 0.35;
    cfg.operating_point.calibration_seeds = [1729, 2718];  % train/val only; never test
    cfg.operating_point.candidate_input_scaling = [0.25, 0.5, 0.75, 1.0];
    cfg.operating_point.candidate_level_of_chaos = [0.6, 0.8, 1.0, 1.2];
    cfg.operating_point.rule = [ ...
        'Shared calibration: pick the first (input_scaling, level_of_chaos) pair ', ...
        'that keeps mean rate and saturation within bands on ALL paired mechanism ', ...
        'conditions for calibration seeds. Never select by final task test score.'];

    %% Build cell tables per analysis set (using current base.n for feature dims)
    n = cfg.base.n;
    cfg.cells_by_analysis_set = struct();
    cfg.cells_by_analysis_set.confirmatory = build_cell_table( ...
        confirmatory_adapt, ...
        select_levels(std_levels, {'off', 'on'}), ...
        select_levels(delay_levels, {'ode_off', 'dde_on'}), ...
        select_levels(feature_levels, {'x', 'r'}), ...
        'confirmatory', n);
    cfg.cells_by_analysis_set.sfa_sensitivity = build_cell_table( ...
        sensitivity_adapt, ...
        select_levels(std_levels, {'off'}), ...
        select_levels(delay_levels, {'ode_off'}), ...
        select_levels(feature_levels, {'x', 'r'}), ...
        'sfa_sensitivity', n);
    cfg.cells_by_analysis_set.feature_exploratory = build_cell_table( ...
        confirmatory_adapt, ...
        select_levels(std_levels, {'off'}), ...
        select_levels(delay_levels, {'ode_off'}), ...
        select_levels(feature_levels, {'all'}), ...
        'feature_exploratory', n);

    assert(numel(cfg.cells_by_analysis_set.confirmatory) == 24, ...
        'mechanism_ablation_config:ConfirmatoryCount', ...
        'Confirmatory set must have exactly 24 cells per seed.');
    assert(numel(cfg.cells_by_analysis_set.sfa_sensitivity) == 12, ...
        'mechanism_ablation_config:SensitivityCount', ...
        'SFA sensitivity set must have exactly 12 cells per seed.');
    assert(numel(cfg.cells_by_analysis_set.feature_exploratory) == 3, ...
        'mechanism_ablation_config:ExploratoryCount', ...
        'Feature exploratory set must have exactly 3 cells per seed.');

    cfg.cells = cfg.cells_by_analysis_set.(analysis_set);
    cfg.n_cells = numel(cfg.cells);
    cfg.n_seeds = numel(cfg.seeds);
    cfg.n_paired_runs = cfg.n_cells * cfg.n_seeds;

    % Active factor snapshot for fingerprints / manifests
    cfg.factors = struct();
    switch analysis_set
        case 'confirmatory'
            cfg.factors.adaptation = confirmatory_adapt;
            cfg.factors.std = select_levels(std_levels, {'off', 'on'});
            cfg.factors.delay = select_levels(delay_levels, {'ode_off', 'dde_on'});
            cfg.factors.readout_features = select_levels(feature_levels, {'x', 'r'});
        case 'sfa_sensitivity'
            cfg.factors.adaptation = sensitivity_adapt;
            cfg.factors.std = select_levels(std_levels, {'off'});
            cfg.factors.delay = select_levels(delay_levels, {'ode_off'});
            cfg.factors.readout_features = select_levels(feature_levels, {'x', 'r'});
        case 'feature_exploratory'
            cfg.factors.adaptation = confirmatory_adapt;
            cfg.factors.std = select_levels(std_levels, {'off'});
            cfg.factors.delay = select_levels(delay_levels, {'ode_off'});
            cfg.factors.readout_features = select_levels(feature_levels, {'all'});
    end

    %% Multiple-comparison policy (secondary family; T103)
    cfg.multiple_comparison = struct( ...
        'family', 'secondary_endpoints', ...
        'method', 'holm_bonferroni', ...
        'alpha', 0.05, ...
        'effect_size', 'paired_median_difference_and_cliff_delta', ...
        'note', [ ...
            'Do not combine sfa_sensitivity or feature_exploratory cells into ', ...
            'the confirmatory multiple-comparison family.']);

    %% Unsupported metric status strings
    cfg.unsupported_status = struct( ...
        'dde_lle', 'unsupported_not_computed', ...
        'dde_autonomous', 'unsupported_not_computed', ...
        'fisher_memory', 'unsupported_not_computed');

    %% Temporal learning gate (Phase 4B) — implementation validity, not a paper endpoint
    cfg.temporal_learning_gate = build_temporal_learning_gate(cfg, mode_in);

    %% Matched one-step task baselines (Phase 4C-A)
    cfg.benchmark_baselines = build_matched_task_baselines_config(cfg);

    %% Mackey–Glass autonomous ODE rollout (Phase 4C-B1; secondary endpoint)
    cfg.mg_autonomous_rollout = build_mg_autonomous_rollout_config(mode_in);

    %% Deterministic protocol identity (after all frozen fields are set)
    cfg.protocol_fingerprint = compute_protocol_fingerprint(cfg);
end

function gate = build_temporal_learning_gate(cfg, mode_in)
% Preregistered delayed-input reservoir learning gate (no include_input).
    ref = find_reference_learning_cell(cfg.cells_by_analysis_set.confirmatory);
    thr = struct( ...
        'mesn_median_nrmse_max', 0.90, ...
        'mesn_median_r2_min', 0.15, ...
        'median_delta_vs_current_min', 0.10, ...
        'fraction_beating_current_min', 0.80, ...
        'median_delta_vs_no_recurrence_min', 0.02, ...
        'fraction_beating_no_recurrence_min', 0.60, ...
        'shuffled_median_nrmse_min', 0.95, ...
        'exact_history_median_nrmse_max', 1e-6);

    gate = struct();
    gate.enabled = true;
    gate.protocol_version = 'temporal_learning_gate_v1';
    gate.role = 'implementation_validity_not_paper_endpoint';
    gate.input_distribution = 'iid_uniform';
    gate.input_min = -1;
    gate.input_max = 1;
    gate.target_definition = 'y(t)=u(t-k)';
    gate.target_lag_steps = 10;
    gate.dt = cfg.base.dt;
    gate.target_lag_time = gate.target_lag_steps * gate.dt;
    gate.feature_mode = 'r';
    gate.include_input = false;
    gate.feature_dimension = cfg.base.n;  % which_states=r, no raw input
    gate.lambda_grid = [0, logspace(-12, 2, 15)];
    gate.thresholds = thr;
    gate.controls = { ...
        'current_input_only_control', ...
        'no_recurrent_coupling_control', ...
        'shuffled_target_control', ...
        'exact_history_control'};
    gate.reference_cell_key = ref.cell_key;
    gate.reference_cell = ref;
    gate.reference_description = [ ...
        'Publication reference MESN: multi-timescale excitatory SFA ', ...
        '(three_timescales), frozen single-timescale inhibitory SFA, ', ...
        'STD on, inhibitory delay on, feature_mode=r, include_input=false.'];

    % Task / shuffle seeds independent of model seeds
    gate.train_input_seed = 9001;
    gate.validation_input_seed = 9002;
    gate.test_input_seed = 9003;
    gate.shuffle_train_seed = 9101;
    gate.shuffle_validation_seed = 9102;
    gate.shuffle_test_seed = 9103;

    switch mode_in
        case 'publication'
            gate.model_seeds = [1729, 2718, 31415, 10007, 10009];
            gate.washout_steps = 200;
            gate.train_samples = 4000;
            gate.validation_samples = 1000;
            gate.test_samples = 2000;
            gate.ode_reltol = 1e-6;
            gate.ode_abstol = 1e-8;
            gate.dde_reltol = 1e-6;
            gate.dde_abstol = 1e-8;
        case {'smoke', 'pilot'}
            % Same target/controls/metrics/thresholds; reduced lengths/seeds.
            gate.model_seeds = [1729, 2718, 31415];
            gate.washout_steps = 40;
            gate.train_samples = 250;
            gate.validation_samples = 80;
            gate.test_samples = 120;
            gate.ode_reltol = 1e-4;
            gate.ode_abstol = 1e-6;
            gate.dde_reltol = 1e-4;
            gate.dde_abstol = 1e-6;
            gate.length_note = 'smoke_or_pilot_reduced_never_publication_evidence';
        otherwise
            error('mechanism_ablation_config:BadGateTier', 'Unknown protocol_tier.');
    end
end

function cell_spec = find_reference_learning_cell(cells)
    key = 'adapt-three_timescales__std-on__delay-dde_on__feat-r';
    for i = 1:numel(cells)
        if strcmp(cells{i}.cell_key, key)
            cell_spec = cells{i};
            return;
        end
    end
    error('mechanism_ablation_config:MissingLearningGateCell', ...
        'Reference cell %s not found in confirmatory set.', key);
end

function profiles = build_adaptation_profiles(c_total_E, c_total_I, tau_a_I, c_a_I)
% Explicit publication adaptation profiles (no logspace).
    I_common_desc = [ ...
        'Common single-timescale inhibitory SFA (tau_a_I=0.25, c_total_I) ', ...
        'held fixed across non-off profiles.'];

    profiles = { ...
        make_profile('off', 0, 0, zeros(1, 0), zeros(1, 0), ...
            zeros(1, 0), zeros(1, 0), 'confirmatory', 'confirmatory', ...
            ['No SFA. Control with adaptation states absent. ', I_common_desc]), ...
        make_profile('single_fast', 1, 1, 0.25, tau_a_I, ...
            c_total_E, c_a_I, 'control', 'sfa_sensitivity', ...
            ['Single fast excitatory SFA (tau=0.25) with total E coupling. ', I_common_desc]), ...
        make_profile('single_middle', 1, 1, 2.5, tau_a_I, ...
            c_total_E, c_a_I, 'control', 'sfa_sensitivity', ...
            ['Single middle excitatory SFA (tau=2.5) with total E coupling. ', I_common_desc]), ...
        make_profile('single_slow', 1, 1, 25, tau_a_I, ...
            c_total_E, c_a_I, 'control', 'sfa_sensitivity', ...
            ['Single slow excitatory SFA (tau=25) with total E coupling. ', I_common_desc]), ...
        make_profile('single_moment_matched', 1, 1, 9.25, tau_a_I, ...
            c_total_E, c_a_I, 'confirmatory', 'confirmatory', ...
            ['Moment-matched single E filter tau_eff=9.25 matching DC and first ', ...
             'temporal moment of equal-weight [0.25,2.5,25] (not all frequencies). ', ...
             I_common_desc]), ...
        make_profile('three_timescales', 3, 1, [0.25, 2.5, 25], tau_a_I, ...
            ones(1, 3) * (c_total_E / 3), c_a_I, 'confirmatory', 'confirmatory', ...
            ['Three equal-weight excitatory timescales. Manipulated mechanism: ', ...
             'multi-timescale excitatory SFA with common single-timescale inhibitory SFA. ', ...
             I_common_desc]), ...
        make_profile('three_identical_dimension_control', 3, 1, ...
            [9.25, 9.25, 9.25], tau_a_I, ...
            ones(1, 3) * (c_total_E / 3), c_a_I, 'control', 'sfa_sensitivity', ...
            ['Dimension control: three identical moment-matched E filters. With ', ...
             'paired_weighted_match init, dynamically equivalent to single_moment_matched ', ...
             'apart from duplicated state representation. ', I_common_desc]) ...
        };
end

