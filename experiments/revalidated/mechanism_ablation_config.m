        analysis_role, analysis_set, scientific_description)
    p = struct();
    p.label = label;
    p.n_a_E = n_a_E;
    p.n_a_I = n_a_I;
    p.tau_a_E = tau_a_E;
    p.tau_a_I = tau_a_I;
    p.c_a_E = c_a_E;
    p.c_a_I = c_a_I;
    p.analysis_role = analysis_role;
    p.analysis_set = analysis_set;
    p.scientific_description = scientific_description;
end

function policy = build_feature_policy()
    policy = struct();
    policy.x = struct( ...
        'label', 'x', ...
        'which_states', 'x', ...
        'feature_analysis_role', 'confirmatory', ...
        'dimension_matched', true, ...
        'notes', 'Fixed dimension n dendritic states');
    policy.r = struct( ...
        'label', 'r', ...
        'which_states', 'r', ...
        'feature_analysis_role', 'confirmatory', ...
        'dimension_matched', true, ...
        'notes', 'Fixed dimension n firing rates');
    policy.all = struct( ...
        'label', 'all', ...
        'which_states', 'all', ...
        'feature_analysis_role', 'exploratory', ...
        'dimension_matched', false, ...
        'notes', [ ...
            'Mechanism-dependent raw packed-state dimension; exploratory only. ', ...
            'Unmatched all-feature cells must not enter confirmatory comparisons. ', ...
            'Any future training-only projection is deferred to later phases.']);
end

function level = feature_level_from_policy(policy, label)
    level = policy.(label);
end

function selected = profiles_by_label(profiles, labels)
    selected = {};
    for i = 1:numel(labels)
        found = false;
        for j = 1:numel(profiles)
            if strcmp(profiles{j}.label, labels{i})
                selected{end+1} = profiles{j}; %#ok<AGROW>
                found = true;
                break;
            end
        end
        if ~found
            error('mechanism_ablation_config:MissingProfile', ...
                'Adaptation profile ''%s'' not found.', labels{i});
        end
    end
end

function selected = select_levels(levels, labels)
    selected = {};
    for i = 1:numel(labels)
        found = false;
        for j = 1:numel(levels)
            if strcmp(levels{j}.label, labels{i})
                selected{end+1} = levels{j}; %#ok<AGROW>
                found = true;
                break;
            end
        end
        if ~found
            error('mechanism_ablation_config:MissingLevel', ...
                'Factor level ''%s'' not found.', labels{i});
        end
    end
end

function cells = build_cell_table(adapt_levels, std_levels, delay_levels, ...
        feature_levels, analysis_set, n)
    cells = {};
    idx = 0;
    for ia = 1:numel(adapt_levels)
        for is = 1:numel(std_levels)
            for id = 1:numel(delay_levels)
                for ir = 1:numel(feature_levels)
                    idx = idx + 1;
                    a = adapt_levels{ia};
                    s = std_levels{is};
                    d = delay_levels{id};
                    r = feature_levels{ir};

                    if strcmp(r.which_states, 'all') && strcmp(analysis_set, 'confirmatory')
                        error('mechanism_ablation_config:ConfirmatoryAllForbidden', ...
                            'Unmatched all-feature cells cannot be confirmatory.');
                    end
                    if strcmp(r.feature_analysis_role, 'confirmatory') == false && ...
                            strcmp(analysis_set, 'confirmatory')
                        error('mechanism_ablation_config:ConfirmatoryFeatureRole', ...
                            'Confirmatory cells require confirmatory feature_analysis_role.');
                    end

                    cell = struct();
                    cell.cell_id = idx;
                    cell.cell_key = sprintf('adapt-%s__std-%s__delay-%s__feat-%s', ...
                        a.label, s.label, d.label, r.label);
                    cell.adaptation = a.label;
                    cell.adaptation_profile_label = a.label;
                    cell.std = s.label;
                    cell.delay = d.label;
                    cell.readout_features = r.label;
                    cell.analysis_set = analysis_set;
                    cell.analysis_role = a.analysis_role;
                    cell.n_a_E = a.n_a_E;
                    cell.n_a_I = a.n_a_I;
                    cell.tau_a_E = a.tau_a_E;
                    cell.tau_a_I = a.tau_a_I;
                    cell.c_a_E = a.c_a_E;
                    cell.c_a_I = a.c_a_I;
                    cell.n_b_E = s.n_b_E;
                    cell.n_b_I = s.n_b_I;
                    cell.lags = d.lags;
                    cell.which_states = r.which_states;
                    cell.feature_analysis_role = r.feature_analysis_role;
                    cell.dimension_matched = logical(r.dimension_matched);
                    cell.raw_feature_dimension = raw_feature_dimension( ...
                        n, r.which_states, a.n_a_E, a.n_a_I, s.n_b_E, s.n_b_I);
                    if cell.dimension_matched
                        cell.projected_feature_dimension = cell.raw_feature_dimension;
                    else
                        cell.projected_feature_dimension = NaN;  % deferred Phase 4+
                    end
                    cell.mode = ternary(isempty(d.lags), 'ODE', 'DDE');
                    cell.scientific_description = a.scientific_description;
                    cells{end+1} = cell; %#ok<AGROW>
                end
            end
        end
    end
end

function d = raw_feature_dimension(n, which_states, n_a_E, n_a_I, n_b_E, n_b_I)
    switch which_states
        case {'x', 'r'}
            d = n;
        case 'all'
            n_E = round(n * 0.5);
            n_I = n - n_E;
            d = n_E * n_a_E + n_I * n_a_I + n_E * n_b_E + n_I * n_b_I + n;
        otherwise
            error('mechanism_ablation_config:InvalidWhichStates', ...
                'which_states must be x, r, or all.');
    end
end

