function cfg = mechanism_ablation_config(mode)
% mechanism_ablation_config  Preregistered MESN mechanism-ablation matrix.
%
%   cfg = mechanism_ablation_config()
%   cfg = mechanism_ablation_config('pilot')   % reduced lengths, 3 seeds
%   cfg = mechanism_ablation_config('full')    % publication lengths, >=30 seeds
%
% Returns a frozen configuration table BEFORE any outcomes are generated.
% Fairness: total adaptation coupling is held constant across adaptation levels
% using T35 vectors c_a_E / c_a_I (equal weights summing to the single-timescale
% totals). Do not triple total strength by adding filters.
%
% See also: docs/validation/EXPERIMENT_PREREGISTRATION.md

    if nargin < 1 || isempty(mode)
        mode = 'full';
    end
    mode = char(mode);

    % Fixed totals from resolve_adaptation_coupling defaults (T35).
    c_total_E = 0.1 / 7;
    c_total_I = 0.1 / 4;

    cfg = struct();
    cfg.experiment_name = 'mechanism_ablation';
    cfg.preregistration_doc = 'docs/validation/EXPERIMENT_PREREGISTRATION.md';
    cfg.mode = mode;
    cfg.created_utc = char(datetime('now', 'TimeZone', 'UTC', ...
        'Format', 'yyyy-MM-dd''T''HH:mm:ss''Z'''));

    %% Factor levels (complete Cartesian product)
    cfg.factors = struct();
    cfg.factors.adaptation = { ...
        struct('label', 'off', 'n_a_E', 0, 'n_a_I', 0, ...
            'c_a_E', zeros(1, 0), 'c_a_I', zeros(1, 0)), ...
        struct('label', 'one_timescale', 'n_a_E', 1, 'n_a_I', 1, ...
            'c_a_E', c_total_E, 'c_a_I', c_total_I), ...
        struct('label', 'three_timescales', 'n_a_E', 3, 'n_a_I', 1, ...
            'c_a_E', ones(1, 3) * (c_total_E / 3), ...
            'c_a_I', c_total_I) ...
        };
    cfg.factors.std = { ...
        struct('label', 'off', 'n_b_E', 0, 'n_b_I', 0), ...
        struct('label', 'on',  'n_b_E', 1, 'n_b_I', 1) ...
        };
    cfg.factors.delay = { ...
        struct('label', 'ode_off', 'lags', []), ...
        struct('label', 'dde_on',  'lags', 0.03) ...
        };
    cfg.factors.readout_features = { ...
        struct('label', 'x',   'which_states', 'x'), ...
        struct('label', 'r',   'which_states', 'r'), ...
        struct('label', 'all', 'which_states', 'all') ...
        };

    cfg.c_total_E = c_total_E;
    cfg.c_total_I = c_total_I;
    cfg.fairness_rule = [ ...
        'Keep sum(c_a_E)=c_total_E and sum(c_a_I)=c_total_I across adaptation ', ...
        'levels. Three-timescale E uses equal weights c_total_E/3.'];

    %% Shared base network (paired across ablations)
    cfg.base = struct();
    cfg.base.n = 40;
    cfg.base.fraction_E = 0.5;
    cfg.base.n_inputs = 1;
    cfg.base.dt = 0.1;
    cfg.base.tau_d = 0.55;
    cfg.base.dale = true;
    cfg.base.row_center_W = false;
    cfg.base.W_scale_method = 'abscissa';
    cfg.base.level_of_chaos = 1.0;          % may be overridden by T102 calibration
    cfg.base.input_scaling = 0.5;           % may be overridden by T102 calibration
    cfg.base.input_sparsity = 0.8;
    cfg.base.tau_b_E_rec = 0.6;
    cfg.base.tau_b_E_rel = 0.1;
    cfg.base.tau_b_I_rec = 0.4;
    cfg.base.tau_b_I_rel = 0.5;
    cfg.base.include_input = false;
    cfg.base.lambda = 1e-6;

    %% Seeds
    cfg.pilot_seeds = [1729, 2718, 31415];
    cfg.full_n_seeds = 30;
    % Full experiment: pilot seeds first, then deterministic extensions.
    cfg.full_seeds = unique([cfg.pilot_seeds, ...
        10007, 10009, 10037, 10039, 10061, 10067, 10069, 10079, 10091, 10093, ...
        10099, 10103, 10111, 10133, 10139, 10141, 10151, 10159, 10163, 10169, ...
        10177, 10181, 10193, 10211, 10223, 10243, 10247], 'stable');
    cfg.full_seeds = cfg.full_seeds(1:cfg.full_n_seeds);

    %% Endpoints (declared before outcomes)
    cfg.primary_endpoints = { ...
        'held_out_linear_MC_curve_and_area', ...
        'narma_nrmse', ...
        'mackey_glass_one_step_nrmse', ...
        'empirical_convergence_rate', ...
        'compute_time_seconds' ...
        };
    cfg.secondary_endpoints = { ...
        'nonlinear_capacity', ...
        'frequency_discrimination', ...
        'stimulus_counting', ...
        'effective_rank', ...
        'autonomous_ode_horizon' ...
        };
    cfg.exclusions = { ...
        'invalid_fisher_metric', ...
        'dde_lle', ...
        'dde_autonomous_rollout', ...
        'uncorrected_phase_advance', ...
        'bifurcation_claims' ...
        };

    %% Sequence lengths and task options by mode
    switch lower(mode)
        case 'pilot'
            cfg.seeds = cfg.pilot_seeds;
            cfg.pilot_not_for_publication = true;
            cfg.base.n = 12;  % reduced network for pipeline QA only
            cfg.lengths = struct( ...
                'mc_lags', 1:6, ...
                'mc_washout', 15, ...
                'mc_T_train', 180, ...
                'mc_T_val', 90, ...
                'mc_T_test', 90, ...
                'mc_minimum_scored_rows', 30, ...
                'mc_n_chance', 10, ...
                'narma_T', 280, ...
                'narma_washout', 15, ...
                'narma_order', 10, ...
                'mg_T', 280, ...
                'mg_discard', 80, ...
                'mg_washout', 15, ...
                'mg_do_rollout', false, ...
                'esp_T', 120, ...
                'esp_washout', 15, ...
                'esp_n_ic', 3, ...
                'esp_min_tail_points', 20, ...
                'train_ratio', 0.6, ...
                'val_ratio', 0.2, ...
                'lambda_grid', [1e-6, 1e-4, 1e-2, 1], ...
                'ode_reltol', 1e-4, ...
                'ode_abstol', 1e-6, ...
                'dde_reltol', 1e-4, ...
                'dde_abstol', 1e-6, ...
                'ode_solver', @ode45);
            cfg.secondary_enabled = false;  % pilot: primary endpoints only
        case 'full'
            cfg.seeds = cfg.full_seeds;
            cfg.pilot_not_for_publication = false;
            cfg.lengths = struct( ...
                'mc_lags', 1:50, ...
                'mc_washout', 100, ...
                'mc_T_train', 1500, ...
                'mc_T_val', 500, ...
                'mc_T_test', 500, ...
                'mc_minimum_scored_rows', 50, ...
                'mc_n_chance', 100, ...
                'narma_T', 3000, ...
                'narma_washout', 100, ...
                'narma_order', 10, ...
                'mg_T', 3000, ...
                'mg_discard', 500, ...
                'mg_washout', 100, ...
                'mg_do_rollout', true, ...
                'esp_T', 800, ...
                'esp_washout', 100, ...
                'esp_n_ic', 6, ...
                'esp_min_tail_points', 20, ...
                'train_ratio', 0.6, ...
                'val_ratio', 0.2, ...
                'lambda_grid', [], ...
                'ode_reltol', 1e-6, ...
                'ode_abstol', 1e-8, ...
                'dde_reltol', 1e-6, ...
                'dde_abstol', 1e-8);
            cfg.secondary_enabled = true;
        otherwise
            error('mechanism_ablation_config:InvalidMode', ...
                'mode must be ''pilot'' or ''full'', got %s.', mode);
    end

    %% Operating-point bands (T102); frozen before full experiment
    cfg.operating_point = struct();
    cfg.operating_point.mean_rate_band = [0.05, 0.85];
    cfg.operating_point.saturation_fraction_max = 0.35;
    cfg.operating_point.silent_fraction_max = 0.35;
    cfg.operating_point.calibration_seeds = [1729, 2718];  % train/val only; never test
    cfg.operating_point.candidate_input_scaling = [0.25, 0.5, 0.75, 1.0];
    cfg.operating_point.candidate_level_of_chaos = [0.6, 0.8, 1.0, 1.2];
    cfg.operating_point.rule = [ ...
        'Shared calibration: pick the first (input_scaling, level_of_chaos) pair ', ...
        'that keeps mean rate and saturation within bands on ALL paired mechanism ', ...
        'conditions for calibration seeds. Never select by final task test score.'];

    %% Build complete cell table before outcomes
    cfg.cells = build_cell_table(cfg);
    cfg.n_cells = numel(cfg.cells);
    cfg.n_seeds = numel(cfg.seeds);
    cfg.n_paired_runs = cfg.n_cells * cfg.n_seeds;

    %% Multiple-comparison policy (secondary family; T103)
    cfg.multiple_comparison = struct( ...
        'family', 'secondary_endpoints', ...
        'method', 'holm_bonferroni', ...
        'alpha', 0.05, ...
        'effect_size', 'paired_median_difference_and_cliff_delta');

    %% Unsupported metric status strings
    cfg.unsupported_status = struct( ...
        'dde_lle', 'unsupported_not_computed', ...
        'dde_autonomous', 'unsupported_not_computed', ...
        'fisher_memory', 'unsupported_not_computed');
end

function cells = build_cell_table(cfg)
    cells = {};
    idx = 0;
    for ia = 1:numel(cfg.factors.adaptation)
        for is = 1:numel(cfg.factors.std)
            for id = 1:numel(cfg.factors.delay)
                for ir = 1:numel(cfg.factors.readout_features)
                    idx = idx + 1;
                    a = cfg.factors.adaptation{ia};
                    s = cfg.factors.std{is};
                    d = cfg.factors.delay{id};
                    r = cfg.factors.readout_features{ir};
                    cell = struct();
                    cell.cell_id = idx;
                    cell.cell_key = sprintf('adapt-%s__std-%s__delay-%s__feat-%s', ...
                        a.label, s.label, d.label, r.label);
                    cell.adaptation = a.label;
                    cell.std = s.label;
                    cell.delay = d.label;
                    cell.readout_features = r.label;
                    cell.n_a_E = a.n_a_E;
                    cell.n_a_I = a.n_a_I;
                    cell.c_a_E = a.c_a_E;
                    cell.c_a_I = a.c_a_I;
                    cell.n_b_E = s.n_b_E;
                    cell.n_b_I = s.n_b_I;
                    cell.lags = d.lags;
                    cell.which_states = r.which_states;
                    cell.mode = ternary(isempty(d.lags), 'ODE', 'DDE');
                    cells{end+1} = cell; %#ok<AGROW>
                end
            end
        end
    end
end

function out = ternary(cond, a, b)
    if cond
        out = a;
    else
        out = b;
    end
end
