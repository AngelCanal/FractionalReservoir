function fingerprint = compute_temporal_memory_development_fingerprint(cfg)
% compute_temporal_memory_development_fingerprint  Development protocol SHA-256.
%
%   fingerprint = compute_temporal_memory_development_fingerprint(cfg)
%
% Hashes scientifically frozen development-diagnostic fields only. Excludes
% timestamps, paths, hostnames, runtime metadata, and protocol_fingerprint.

    if nargin < 1 || ~isstruct(cfg)
        error('compute_temporal_memory_development_fingerprint:InvalidCfg', ...
            'cfg must be a struct.');
    end

    include = { ...
        'experiment_name', ...
        'preregistration_doc', ...
        'seed_ledger_doc', ...
        'protocol_version', ...
        'protocol_role', ...
        'protocol_tier', ...
        'publication_evidence', ...
        'can_satisfy_publication_readiness', ...
        'publication_ready', ...
        'architecture_version', ...
        'pilot_not_for_publication', ...
        'seed_ledger', ...
        'v1_observed', ...
        'retired_from_future_publication', ...
        'reserved_future_v2', ...
        'forbidden_executed_seeds', ...
        'model_seeds', ...
        'seeds', ...
        'n_seeds', ...
        'task_seeds', ...
        'shuffle_seeds', ...
        'base', ...
        'frozen_operating_point', ...
        'operating_point_note', ...
        'input_distribution', ...
        'input_min', ...
        'input_max', ...
        'include_input', ...
        'lags', ...
        'primary_diagnostic_lag', ...
        'lambda_grid', ...
        'lengths', ...
        'diagnostic_cells', ...
        'cells', ...
        'diagnostic_cell_names', ...
        'n_cells', ...
        'n_paired_runs', ...
        'per_lag_endpoints', ...
        'per_seed_endpoints', ...
        'primary_endpoints', ...
        'controls', ...
        'conventional_baseline_policy', ...
        'materiality_rules' ...
        };

    payload = struct();
    for i = 1:numel(include)
        name = include{i};
        if isfield(cfg, name)
            payload.(name) = cfg.(name);
        end
    end
    fingerprint = canonical_sha256(payload);
end
