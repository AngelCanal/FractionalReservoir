function hex = temporal_memory_seed_result_content_hash(scored)
%TEMPORAL_MEMORY_SEED_RESULT_CONTENT_HASH  Canonical MESN cell-result semantic hash.
%
%   hex = temporal_memory_seed_result_content_hash(scored)
%
% Single source of truth for runner and validator. Any scientific field change
% must change the hash. Does not embed this hash inside the payload.

    if nargin < 1 || ~isstruct(scored)
        error('temporal_memory_seed_result_content_hash:Invalid', ...
            'scored must be a struct.');
    end
    hex = canonical_sha256(temporal_memory_seed_result_hash_payload(scored));
end

function payload = temporal_memory_seed_result_hash_payload(scored)
    payload = struct();
    payload.model_seed = local_get(scored, 'model_seed', NaN);
    payload.cell_name = char(string(local_get(scored, 'cell_name', '')));
    payload.cell_key = char(string(local_get(scored, 'cell_key', '')));
    payload.feature_mode = char(string(local_get(scored, 'feature_mode', '')));
    payload.feature_dimension = local_get(scored, 'feature_dimension', NaN);
    payload.include_input = logical(local_get(scored, 'include_input', false));
    payload.lags = local_get(scored, 'lags', [])';
    payload.lambda_grid = local_get(scored, 'lambda_grid', [])';
    payload.provenance = char(string(local_get(scored, 'provenance', '')));
    payload.simulations_per_split = local_get(scored, 'simulations_per_split', NaN);
    payload.n_reservoir_simulations = local_get(scored, 'n_reservoir_simulations', NaN);
    payload.global_rng_unchanged = logical(local_get(scored, 'global_rng_unchanged', false));
    payload.W_in_content_hash = resolve_win_hash(scored);
    payload.W_content_hash = resolve_w_hash(scored);
    payload.fit_identity = local_get(scored, 'fit_identity', struct());
    payload.is_test_fixture = logical(local_get(scored, 'is_test_fixture', false));
    payload.synthetic_provenance = logical(local_get(scored, 'synthetic_provenance', false));

    per_lag = local_get(scored, 'per_lag', []);
    n = numel(per_lag);
    lag_rows = repmat(struct( ...
        'lag', NaN, ...
        'rmse', NaN, ...
        'nrmse', NaN, ...
        'r2', NaN, ...
        'pearson', NaN, ...
        'memory_coefficient', NaN, ...
        'constant_prediction', false, ...
        'selected_lambda', NaN, ...
        'grid_boundary_flag', false, ...
        'numerical_rank', NaN, ...
        'coefficient_norm', NaN, ...
        'intercept', NaN, ...
        'coefficient_vector_content_hash', '', ...
        'feature_mean_content_hash', '', ...
        'feature_scale_content_hash', '', ...
        'lambda_selection_table_content_hash', '', ...
        'prediction_vector_content_hash', ''), max(n, 1), 1);
    if n == 0
        lag_rows = lag_rows([]);
    else
        for i = 1:n
            pl = per_lag(i);
            m = local_get(pl, 'metrics', struct());
            lag_rows(i).lag = local_get(pl, 'lag', NaN);
            lag_rows(i).rmse = local_get(m, 'rmse', NaN);
            lag_rows(i).nrmse = local_get(m, 'nrmse', NaN);
            lag_rows(i).r2 = local_get(m, 'r2', NaN);
            lag_rows(i).pearson = local_get(m, 'pearson', ...
                local_get(m, 'pearson_correlation', NaN));
            lag_rows(i).memory_coefficient = local_get(m, 'memory_coefficient', NaN);
            lag_rows(i).constant_prediction = logical(local_get(m, ...
                'constant_prediction', false));
            lag_rows(i).selected_lambda = local_get(pl, 'selected_lambda', NaN);
            lag_rows(i).grid_boundary_flag = logical(local_get(pl, ...
                'selected_at_grid_boundary', local_get(pl, 'grid_boundary_flag', false)));
            lag_rows(i).numerical_rank = local_get(pl, 'numerical_rank', NaN);
            lag_rows(i).coefficient_norm = local_get(pl, 'coefficient_norm', NaN);
            lag_rows(i).intercept = local_get(pl, 'intercept', NaN);
            lag_rows(i).coefficient_vector_content_hash = content_hash_if_present(pl, ...
                'coefficients');
            lag_rows(i).feature_mean_content_hash = content_hash_if_present(pl, ...
                'feature_mean');
            lag_rows(i).feature_scale_content_hash = content_hash_if_present(pl, ...
                'feature_scale');
            lag_rows(i).lambda_selection_table_content_hash = content_hash_if_present(pl, ...
                'lambda_selection_table');
            if isfield(pl, 'y_hat') && ~isempty(pl.y_hat)
                lag_rows(i).prediction_vector_content_hash = canonical_sha256(pl.y_hat);
            elseif isfield(pl, 'predictions') && ~isempty(pl.predictions)
                lag_rows(i).prediction_vector_content_hash = canonical_sha256(pl.predictions);
            else
                lag_rows(i).prediction_vector_content_hash = '';
            end
        end
    end
    payload.per_lag = lag_rows;

    s = local_get(scored, 'summary', struct());
    payload.summary = struct( ...
        'MC_1_10', local_get(s, 'MC_1_10', local_get(s, 'memory_capacity_sum_lags_1_10', NaN)), ...
        'MC_1_25', local_get(s, 'MC_1_25', local_get(s, 'memory_capacity_sum_lags_1_25', NaN)), ...
        'MC_1_50', local_get(s, 'MC_1_50', local_get(s, 'memory_capacity_sum_lags_1_50', NaN)), ...
        'maximum_memory_lag', local_get(s, 'maximum_memory_lag', ...
            local_get(s, 'lag_of_maximum_memory_coefficient', NaN)), ...
        'maximum_memory_coefficient', local_get(s, 'maximum_memory_coefficient', NaN), ...
        'first_crossing_below_0_1', local_get(s, 'first_lag_memory_below_0_1', NaN), ...
        'right_censoring_flag', logical(local_get(s, ...
            'memory_crossing_right_censored_at_50', false)), ...
        'lag10_nrmse', local_get(s, 'lag10_nrmse', NaN), ...
        'lag10_r2', local_get(s, 'lag10_r2', NaN), ...
        'lag10_rmse', local_get(s, 'lag10_rmse', NaN), ...
        'lag10_pearson', local_get(s, 'lag10_pearson', NaN), ...
        'lag10_memory_coefficient', local_get(s, 'lag10_memory_coefficient', NaN));

    fd = local_get(scored, 'feature_diagnostics', struct());
    payload.feature_diagnostics = struct( ...
        'numerical_rank', local_get(fd, 'numerical_rank', NaN), ...
        'rank_tolerance', local_get(fd, 'rank_tolerance', NaN), ...
        'participation_ratio', local_get(fd, 'participation_ratio', ...
            local_get(fd, 'feature_participation_ratio', NaN)), ...
        'near_constant_fraction', local_get(fd, ...
            'fraction_numerically_near_constant_features', ...
            local_get(fd, 'fraction_near_constant', NaN)), ...
        'mean_feature_standard_deviation', local_get(fd, ...
            'mean_feature_standard_deviation', NaN), ...
        'median_feature_standard_deviation', local_get(fd, ...
            'median_feature_standard_deviation', NaN), ...
        'median_absolute_offdiag_feature_correlation', local_get(fd, ...
            'median_absolute_offdiag_feature_correlation', NaN), ...
        'maximum_absolute_offdiag_feature_correlation', local_get(fd, ...
            'maximum_absolute_offdiag_feature_correlation', NaN), ...
        'mean_firing_rate', local_get(fd, 'mean_firing_rate', NaN), ...
        'saturation_fraction', local_get(fd, 'saturation_fraction', NaN), ...
        'silence_fraction', local_get(fd, 'silence_fraction', NaN), ...
        'n_neurons', local_get(fd, 'n_neurons', NaN), ...
        'packed_state_dimension', local_get(fd, 'packed_state_dimension', NaN), ...
        'activity_from_neuronal_rates', logical(local_get(fd, ...
            'activity_from_neuronal_rates', false)), ...
        'packed_states_counted_as_neurons', logical(local_get(fd, ...
            'packed_states_counted_as_neurons', false)));
end

function hex = resolve_win_hash(scored)
    computed = '';
    if isfield(scored, 'W_in') && ~isempty(scored.W_in)
        computed = canonical_sha256(scored.W_in);
    end
    if isfield(scored, 'W_in_hash') && ~isempty(scored.W_in_hash)
        stored = char(scored.W_in_hash);
        if ~isempty(computed) && ~strcmp(stored, computed)
            error('temporal_memory_seed_result_content_hash:WinHashMismatch', ...
                'W_in_hash does not match W_in for cell %s.', ...
                char(string(local_get(scored, 'cell_name', ''))));
        end
        hex = stored;
    elseif ~isempty(computed)
        hex = computed;
    else
        hex = '';
    end
end

function hex = resolve_w_hash(scored)
    computed = '';
    if isfield(scored, 'W') && ~isempty(scored.W)
        computed = canonical_sha256(scored.W);
    end
    if isfield(scored, 'W_hash') && ~isempty(scored.W_hash)
        stored = char(scored.W_hash);
        if ~isempty(computed) && ~strcmp(stored, computed)
            error('temporal_memory_seed_result_content_hash:WHashMismatch', ...
                'W_hash does not match W for cell %s.', ...
                char(string(local_get(scored, 'cell_name', ''))));
        end
        hex = stored;
    elseif ~isempty(computed)
        hex = computed;
    else
        hex = '';
    end
end

function hex = content_hash_if_present(s, field)
    if isfield(s, field) && ~isempty(s.(field))
        hex = canonical_sha256(s.(field));
    else
        hex = '';
    end
end

function v = local_get(s, name, default)
    if isstruct(s) && isfield(s, name) && ~isempty(s.(name))
        v = s.(name);
    else
        v = default;
    end
end
