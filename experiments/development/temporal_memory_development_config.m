function cfg = temporal_memory_development_config()
% temporal_memory_development_config  Development-only MESN memory diagnostics.
%
%   cfg = temporal_memory_development_config()
%
% Preregisters protocol identity, seed roles, diagnostic cells, endpoints, and
% descriptive materiality rules for investigating why non-fractional MESN v1
% narrowly failed temporal_learning_gate_v1.
%
% This protocol can never satisfy publication readiness. It does not modify
% temporal_learning_gate_v1 or mechanism_ablation_config.
%
% See also: docs/validation/TEMPORAL_MEMORY_DEVELOPMENT_PREREGISTRATION.md
%           docs/validation/SEED_ROLE_LEDGER.md

    cfg = struct();
    cfg.experiment_name = 'temporal_memory_development_diagnostics';
    cfg.preregistration_doc = ...
        'docs/validation/TEMPORAL_MEMORY_DEVELOPMENT_PREREGISTRATION.md';
    cfg.seed_ledger_doc = 'docs/validation/SEED_ROLE_LEDGER.md';
    cfg.created_utc = char(datetime('now', 'TimeZone', 'UTC', ...
        'Format', 'yyyy-MM-dd''T''HH:mm:ss''Z'''));

    %% Protocol identity (frozen)
    cfg.protocol_version = 'temporal_memory_diagnostic_v1';
    cfg.protocol_role = 'development_only_architecture_diagnosis';
    cfg.protocol_tier = 'development';
    cfg.publication_evidence = false;
    cfg.can_satisfy_publication_readiness = false;
    cfg.publication_ready = false;
    cfg.architecture_version = 'nonfractional_mesn_v1';
    cfg.pilot_not_for_publication = true;

    %% Seed ledger (roles; execution policy enforced by validator)
    ledger = build_seed_ledger();
    cfg.seed_ledger = ledger;
    cfg.v1_observed = ledger.v1_observed;
    cfg.retired_from_future_publication = ledger.retired_from_future_publication;
    cfg.reserved_future_v2 = ledger.reserved_future_v2;
    cfg.forbidden_executed_seeds = ledger.forbidden_executed_seeds;

    %% Development seeds permitted for execution
    cfg.model_seeds = ledger.development.model_seeds(:)';
    cfg.seeds = cfg.model_seeds;
    cfg.n_seeds = numel(cfg.model_seeds);
    cfg.task_seeds = ledger.development.task_seeds;
    cfg.shuffle_seeds = ledger.development.shuffle_seeds;

    %% Diagnostic geometry (copied from v1 operating point; not recalibrated)
    cfg.base = struct();
    cfg.base.n = 40;
    cfg.base.fraction_E = 0.5;
    cfg.base.n_inputs = 1;
    cfg.base.dt = 0.1;
    cfg.base.tau_d = 0.55;
    cfg.base.dale = true;
    cfg.base.row_center_W = false;
    cfg.base.W_scale_method = 'abscissa';
    cfg.base.input_scaling = 0.25;
    cfg.base.level_of_chaos = 0.60;
    cfg.base.input_sparsity = 0.8;
    cfg.base.input_mask_mode = 'fixed_count';
    cfg.base.adaptation_initialization_mode = 'paired_weighted_match';
    cfg.base.tau_b_E_rec = 0.6;
    cfg.base.tau_b_E_rel = 0.1;
    cfg.base.tau_b_I_rec = 0.4;
    cfg.base.tau_b_I_rel = 0.5;
    cfg.base.include_input = false;
    cfg.base.lambda = 1e-6;

    cfg.frozen_operating_point = struct( ...
        'input_scaling', 0.25, ...
        'level_of_chaos', 0.60, ...
        'candidate_index', 1, ...
        'source', 'temporal_learning_gate_v1_sealed_operating_point');
    cfg.operating_point_note = [ ...
        'Operating point copied from sealed temporal_learning_gate_v1 solely ', ...
        'to diagnose the failure. It is not being recalibrated.'];

    cfg.input_distribution = 'iid_uniform';
    cfg.input_min = -1;
    cfg.input_max = 1;
    cfg.include_input = false;
    cfg.lags = 1:50;
    cfg.primary_diagnostic_lag = 10;
    cfg.lambda_grid = [0, logspace(-12, 2, 15)];

    cfg.lengths = struct( ...
        'washout_steps', 200, ...
        'train_samples', 4000, ...
        'validation_samples', 1000, ...
        'test_samples', 2000, ...
        'ode_reltol', 1e-6, ...
        'ode_abstol', 1e-8, ...
        'dde_reltol', 1e-6, ...
        'dde_abstol', 1e-8);

    %% Eight paired diagnostic cells (existing confirmatory cell semantics)
    [cfg.diagnostic_cells, cfg.cells, cfg.diagnostic_cell_names] = ...
        build_diagnostic_cells();
    cfg.n_cells = numel(cfg.cells);
    cfg.n_paired_runs = cfg.n_cells * cfg.n_seeds;
    assert(cfg.n_cells == 8, ...
        'temporal_memory_development_config:CellCount', ...
        'Diagnostic protocol requires exactly eight cells.');

    %% Endpoints (declared before observing outcomes)
    cfg.per_lag_endpoints = { ...
        'held_out_nrmse', ...
        'held_out_r2', ...
        'held_out_pearson_correlation', ...
        'squared_correlation_memory_coefficient', ...
        'selected_lambda', ...
        'grid_boundary_flag', ...
        'effective_numerical_rank', ...
        'coefficient_norm'};

    cfg.per_seed_endpoints = { ...
        'memory_capacity_sum_lags_1_10', ...
        'memory_capacity_sum_lags_1_25', ...
        'memory_capacity_sum_lags_1_50', ...
        'lag_of_maximum_memory_coefficient', ...
        'lag10_nrmse', ...
        'lag10_r2', ...
        'feature_covariance_effective_rank', ...
        'feature_participation_ratio', ...
        'fraction_numerically_near_constant_features', ...
        'mean_feature_standard_deviation', ...
        'median_feature_standard_deviation', ...
        'mean_firing_rate', ...
        'saturation_fraction', ...
        'silence_fraction'};

    cfg.primary_endpoints = [cfg.per_lag_endpoints, cfg.per_seed_endpoints];

    %% Controls (existing implementations only)
    cfg.controls = { ...
        'current_input_only', ...
        'no_recurrent_coupling', ...
        'exact_history', ...
        'shuffled_target_reference_cell', ...
        'matched_conventional_leaky_esn_baseline'};
    cfg.conventional_baseline_policy = [ ...
        'Use existing matched conventional leaky ESN baseline implementations ', ...
        '(build_matched_task_baselines_config / run_conventional_leaky_esn). ', ...
        'Do not create a differently tuned conventional ESN for this protocol.'];

    %% Descriptive materiality rules (frozen before observing outcomes)
    cfg.materiality_rules = struct( ...
        'nrmse_abs_paired_median_difference_min', 0.02, ...
        'r2_abs_paired_median_difference_min', 0.03, ...
        'directional_consistency_requires_all_three_dev_seeds_same_sign', true, ...
        'formal_p_values_forbidden', true, ...
        'confirmatory_inference_with_n3_forbidden', true, ...
        'comparison_role', 'development_hypotheses_only', ...
        'note', [ ...
            'NRMSE difference material if abs paired median difference >= 0.02. ', ...
            'R^2 difference material if abs paired median difference >= 0.03. ', ...
            'A mechanism-removal effect is directionally consistent if all three ', ...
            'development seeds have the same sign. No formal p-values or ', ...
            'confirmatory inference with n=3. All comparisons are development ', ...
            'hypotheses only.']);

    %% Deterministic protocol identity
    cfg.protocol_fingerprint = compute_temporal_memory_development_fingerprint(cfg);
end

