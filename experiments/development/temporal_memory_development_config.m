function vals = collect_seed_values(S)
    vals = zeros(1, 0);
    if isnumeric(S)
        vals = S(:)';
        return;
    end
    if ~isstruct(S)
        return;
    end
    if numel(S) ~= 1
        for i = 1:numel(S)
            vals = [vals, collect_seed_values(S(i))]; %#ok<AGROW>
        end
        return;
    end
    fn = fieldnames(S);
    for i = 1:numel(fn)
        vals = [vals, collect_seed_values(S.(fn{i}))]; %#ok<AGROW>
    end
end

function [named, cells, names] = build_diagnostic_cells()
% Select eight confirmatory cells by existing cell_key semantics.
    ref_cfg = mechanism_ablation_config('publication', 'confirmatory');
    catalog = ref_cfg.cells_by_analysis_set.confirmatory;

    names = { ...
        'reference_r', ...
        'reference_x', ...
        'delay_removed_r', ...
        'std_removed_r', ...
        'std_and_delay_removed_r', ...
        'single_moment_matched_r', ...
        'adaptation_removed_r', ...
        'mechanisms_off_r'};
    keys = { ...
        'adapt-three_timescales__std-on__delay-dde_on__feat-r', ...
        'adapt-three_timescales__std-on__delay-dde_on__feat-x', ...
        'adapt-three_timescales__std-on__delay-ode_off__feat-r', ...
        'adapt-three_timescales__std-off__delay-dde_on__feat-r', ...
        'adapt-three_timescales__std-off__delay-ode_off__feat-r', ...
        'adapt-single_moment_matched__std-on__delay-dde_on__feat-r', ...
        'adapt-off__std-on__delay-dde_on__feat-r', ...
        'adapt-off__std-off__delay-ode_off__feat-r'};

    named = struct();
    cells = cell(1, numel(names));
    for i = 1:numel(names)
        cell_spec = find_cell_by_key(catalog, keys{i});
        cell_spec.diagnostic_name = names{i};
        cell_spec.diagnostic_cell_id = i;
        named.(names{i}) = cell_spec;
        cells{i} = cell_spec;
    end
end

function cell_spec = find_cell_by_key(cells, key)
    for i = 1:numel(cells)
        if strcmp(cells{i}.cell_key, key)
            cell_spec = cells{i};
            return;
        end
    end
    error('temporal_memory_development_config:MissingCell', ...
        'Required diagnostic cell key not found: %s', key);
end
