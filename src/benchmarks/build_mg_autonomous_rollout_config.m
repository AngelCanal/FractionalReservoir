function cfg = build_mg_autonomous_rollout_config(tier)
% BUILD_MG_AUTONOMOUS_ROLLOUT_CONFIG  Fingerprinted MG ODE autonomous protocol.
%
%   cfg = build_mg_autonomous_rollout_config(tier)
%
% tier: 'smoke' | 'pilot' | 'publication' (pilot shares smoke lengths)
%
% Preregistered secondary endpoint: autonomous_ode_horizon.
% Values are frozen before outcomes; do not tune from test performance.

    if nargin < 1 || isempty(tier)
        tier = 'publication';
    end
    tier = char(tier);

    common = struct( ...
        'enabled', true, ...
        'protocol_version', 'mackey_glass_autonomous_rollout_v1', ...
        'role', 'preregistered_secondary_endpoint', ...
        'supported_mode', 'ODE', ...
        'dde_status', 'unsupported_not_computed', ...
        'include_input', false, ...
        'context_policy', 'all_observed_inputs_through_forecast_origin', ...
        'origin_policy', 'deterministic_evenly_spaced_heldout_origins', ...
        'target_alignment', 'prediction_k_scores_Y(origin+k-1)', ...
        'normalization_reference', 'train_validation_target_std', ...
        'valid_error_threshold', 0.4, ...
        'threshold_sensitivity', [0.2, 0.4, 0.8], ...
        'threshold_sensitivity_role', 'exploratory', ...
        'primary_threshold', 0.4, ...
        'pooled_nrmse_formula', ...
            'sqrt(mean(all_origin_errors(:,1:h).^2))/sigma_ref');

    switch tier
        case {'smoke', 'pilot'}
            cfg = common;
            cfg.forecast_horizon_steps = 20;
            cfg.n_forecast_origins = 2;
            cfg.fixed_report_horizons = [1, 5, 10, 20];
            cfg.length_note = 'smoke_or_pilot_reduced_never_publication_evidence';
        case 'publication'
            cfg = common;
            cfg.forecast_horizon_steps = 100;
            cfg.n_forecast_origins = 5;
            cfg.fixed_report_horizons = [1, 5, 10, 25, 50, 100];
        otherwise
            error('build_mg_autonomous_rollout_config:BadTier', ...
                'tier must be smoke, pilot, or publication, got %s.', tier);
    end
end
